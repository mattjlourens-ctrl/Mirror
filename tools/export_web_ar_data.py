"""Export the live try-on's geometry to TypeScript for the browser.

The website reproduces head_pose.py, accessory_transform.py, fit_controls.py
and occlusion.py in TypeScript. Rather than copy numbers by hand, this writes
them from the Python modules, so both sides share one source of truth:

  frontend/src/lib/ar/generated/web-ar-data.ts   pose landmarks, camera model,
      attachment, fit limits and the head occluder mesh
  frontend/src/lib/ar/generated/pose-fixtures.ts  poses solved by OpenCV and
      projected glasses points, which the TypeScript tests must reproduce

Run after changing any of those modules:
    uv run python tools/export_web_ar_data.py
tests/test_web_ar_data.py fails while the files are out of date.
"""
import json
import math
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import cv2  # noqa: E402

from accessory_transform import (MIN_DEPTH_CM, project_accessory, project_camera_points,  # noqa: E402
                                 transform_points)
from fit_controls import (MAX_OFFSET_CM, MAX_ROTATION_DEGREES, MAX_SCALE, MIN_SCALE,  # noqa: E402
                          FitAdjustment, fit_matrix)
from glasses_3d import DEFAULT_GLASSES_ATTACHMENT  # noqa: E402
from head_pose import (FOCAL_LENGTH_SCALE, FRONTAL_ROTATION, MAX_REPROJECTION_ERROR_RATIO,  # noqa: E402
                       MODEL_POINTS, POSE_LANDMARK_IDS, HeadPose, camera_matrix, estimate_head_pose,
                       euler_angles)
from occlusion import DEPTH_TOLERANCE_CM, load_head_occluder, render_depth_buffer  # noqa: E402

OUTPUT = ROOT / "frontend" / "src" / "lib" / "ar" / "generated"
HEADER = "// Generated by tools/export_web_ar_data.py from Mirror's Python modules. Do not edit.\n"

# Glasses points in glTF metres (model axes): front corners, bridge, temple tips.
SAMPLE_MODEL_POINTS_M = [
    [0.0, 0.0, 0.0], [-0.07, 0.02, 0.0], [0.07, -0.02, 0.0], [0.0, 0.015, 0.002],
    [-0.072, 0.0, -0.13], [0.072, -0.01, -0.13],
]
# Glasses points whose visibility the desktop occlusion decides at several head turns.
OCCLUSION_POINTS_M = {
    "bridge": [0.0, 0.015, 0.002], "leftLens": [-0.04, -0.02, 0.0], "rightLens": [0.04, -0.02, 0.0],
    "leftHinge": [-0.07, 0.005, -0.005], "rightHinge": [0.07, 0.005, -0.005],
    "leftTempleMid": [-0.072, 0.0, -0.06], "rightTempleMid": [0.072, 0.0, -0.06],
    "leftTempleTip": [-0.072, 0.0, -0.13], "rightTempleTip": [0.072, 0.0, -0.13],
}
OCCLUSION_YAWS = [0, 35, -35, 75, -75]
FIT_CASES = [FitAdjustment(), FitAdjustment(scale=1.1, x=0.3, y=-0.4, z=0.2, pitch=4, yaw=-6, roll=3)]
FRAME_SIZE = (1280, 720)


def _round(values, digits=4):
    return [round(float(value), digits) for value in np.ravel(values)]


def _rotation(yaw, pitch, roll):
    """Model -> camera rotation for Mirror's (yaw, pitch, roll) in degrees (see euler_angles)."""
    y, p, r = (math.radians(angle) for angle in (yaw, pitch, roll))
    ry = np.array([[math.cos(y), 0, math.sin(y)], [0, 1, 0], [-math.sin(y), 0, math.cos(y)]])
    rx = np.array([[1, 0, 0], [0, math.cos(-p), -math.sin(-p)], [0, math.sin(-p), math.cos(-p)]])
    rz = np.array([[math.cos(-r), -math.sin(-r), 0], [math.sin(-r), math.cos(-r), 0], [0, 0, 1]])
    return FRONTAL_ROTATION @ ry @ rx @ rz


def web_ar_data():
    occluder = load_head_occluder()
    if occluder is None:
        raise SystemExit("face_landmarker.task is missing; it holds the canonical face mesh")
    return {
        "POSE_LANDMARK_IDS": [int(i) for i in POSE_LANDMARK_IDS],
        "MODEL_POINTS": _round(MODEL_POINTS),
        "FOCAL_LENGTH_SCALE": FOCAL_LENGTH_SCALE,
        "MAX_REPROJECTION_ERROR_RATIO": MAX_REPROJECTION_ERROR_RATIO,
        "MIN_DEPTH_CM": MIN_DEPTH_CM,
        "ANCHOR_CM": _round(DEFAULT_GLASSES_ATTACHMENT.anchor_cm),
        "DEFAULT_OFFSET_CM": _round(DEFAULT_GLASSES_ATTACHMENT.offset_cm),
        "FIT_LIMITS": {"maxOffsetCm": MAX_OFFSET_CM, "maxRotationDegrees": MAX_ROTATION_DEGREES,
                       "minScale": MIN_SCALE, "maxScale": MAX_SCALE},
        "DEPTH_TOLERANCE_CM": DEPTH_TOLERANCE_CM,
        "OCCLUDER_VERTICES": _round(occluder.vertices),
        "OCCLUDER_TRIANGLES": [int(i) for i in occluder.triangles.ravel()],
    }


def pose_fixtures():
    rng = np.random.default_rng(7)
    width, height = FRAME_SIZE
    camera = camera_matrix(width, height)
    cases = []
    poses = [(0, 0, 0, (0, 2, 45)), (25, 0, 0, (3, 0, 50)), (-30, 10, 0, (-4, 3, 55)),
             (0, -15, 12, (2, -2, 40)), (45, 5, -8, (6, 1, 60)), (-55, -10, 5, (-8, 4, 70)),
             (10, 20, -15, (0, 0, 35)), (60, 0, 0, (0, 0, 50))]
    for yaw, pitch, roll, translation in poses:
        rotation = _rotation(yaw, pitch, roll)
        camera_points = MODEL_POINTS @ rotation.T + np.array(translation, float)
        pixels = camera_points[:, :2] / camera_points[:, 2:] * camera[0, 0] + camera[:2, 2]
        pixels = pixels + rng.normal(0, 0.4, pixels.shape)
        pose = estimate_head_pose(pixels, camera)
        case = {"truth": {"yaw": yaw, "pitch": pitch, "roll": roll, "translation": list(translation)},
                "imagePoints": _round(pixels), "pose": None}
        if pose is not None:
            case["pose"] = {"rotation": _round(pose.rotation_matrix, 6),
                            "translation": _round(pose.translation_vector, 4),
                            "euler": _round(euler_angles(pose.rotation_matrix), 3),
                            "projections": []}
            for fit in FIT_CASES:
                matrix = fit_matrix(DEFAULT_GLASSES_ATTACHMENT, fit)
                projected = project_accessory(np.array(SAMPLE_MODEL_POINTS_M) * 100.0, matrix, pose)
                case["pose"]["projections"].append({
                    "fit": {name: getattr(fit, name) for name in ("scale", "x", "y", "z", "pitch", "yaw", "roll")},
                    "pixels": [None if not np.isfinite(p).all() else _round(p, 3) for p in projected]})
        cases.append(case)
    # A face that can't be trusted: points scattered at random.
    cases.append({"truth": None, "imagePoints": _round(rng.uniform(0, 700, (len(MODEL_POINTS), 2))), "pose": None})
    return {"FRAME_SIZE": list(FRAME_SIZE), "SAMPLE_MODEL_POINTS_M": SAMPLE_MODEL_POINTS_M, "CASES": cases,
            "OCCLUSION_POINTS_M": OCCLUSION_POINTS_M, "OCCLUSION_CASES": occlusion_cases()}


def occlusion_cases():
    """Which glasses points occlusion.py hides, for a head 50 cm away turned by each yaw."""
    width, height = FRAME_SIZE
    camera = camera_matrix(width, height)
    occluder = load_head_occluder()
    to_face = fit_matrix(DEFAULT_GLASSES_ATTACHMENT, FitAdjustment())
    cases = []
    for yaw in OCCLUSION_YAWS:
        rotation = _rotation(yaw, 0, 0)
        pose = HeadPose(cv2.Rodrigues(rotation)[0], np.array([[0.0], [0.0], [50.0]]), rotation, camera)
        buffer = render_depth_buffer(occluder, pose, width, height)
        hidden = {}
        for name, point in OCCLUSION_POINTS_M.items():
            camera_point = transform_points(pose.transform @ to_face, np.array([point]) * 100.0)
            x, y = (project_camera_points(camera_point, camera)[0] * buffer.scale).astype(int)
            depth = buffer.depth[y, x] if 0 <= y < buffer.depth.shape[0] and 0 <= x < buffer.depth.shape[1] else np.inf
            hidden[name] = bool(camera_point[0, 2] > depth + DEPTH_TOLERANCE_CM)
        cases.append({"yaw": yaw, "hidden": hidden})
    return cases


def render(values):
    lines = [HEADER]
    for name, value in values.items():
        lines.append(f"export const {name} = {json.dumps(value, separators=(',', ':'))} as const;\n")
    return "\n".join(lines)


def outputs():
    return {OUTPUT / "web-ar-data.ts": render(web_ar_data()),
            OUTPUT / "pose-fixtures.ts": render(pose_fixtures())}


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for path, text in outputs().items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)} ({len(text) // 1024} KB)")


if __name__ == "__main__":
    main()
